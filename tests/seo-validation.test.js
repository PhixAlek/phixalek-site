import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { validateSeo } from '../scripts/lib/seo-validation.mjs';
import { renderWritingHTML, writingSitemap } from '../scripts/lib/writing-render.mjs';
import { homeMetadata } from '../src/shared/site-seo.js';
import snapshot from '../src/content/writing-snapshot.json' with { type: 'json' };
import locale from '../src/content/locales/en.json' with { type: 'json' };

test('deployment validation rejects canonical mismatches, missing image files and indexable error pages', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'phixalek-seo-validation-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const root = pathToFileURL(directory + '/');
  const article = snapshot.articles[0];
  const template = '<!doctype html><html><head></head><body><div id="app"></div></body></html>';
  const options = { messages: locale.messages, fallbackImage: '/media/mountains.svg', profileImage: '/media/avatar.png', siteName: 'PhixAlek' };
  const write = async (file, contents) => { const url = new URL(file, root); await mkdir(new URL('./', url), { recursive: true }); await writeFile(url, contents); };
  await write('media/demome-01.webp', 'fixture');
  await write('index.html', `<html><head><title>${homeMetadata.title}</title><meta name="description" content="Home"><meta name="robots" content="index, follow"><link rel="canonical" href="${homeMetadata.canonical}"><meta property="og:url" content="${homeMetadata.canonical}"><meta property="og:image" content="${homeMetadata.image}"><script type="application/ld+json">{"@type":"Person"}</script></head><body><h1>Alejandro Segura</h1></body></html>`);
  await write('blog/index.html', renderWritingHTML(template, [article], options));
  const post = renderWritingHTML(template, [article], { ...options, article });
  const postFile = `blog/${article.slug}/index.html`;
  await write(postFile, post);
  await write('sitemap.xml', writingSitemap([article]));
  await write('robots.txt', 'User-agent: *\nSitemap: https://phixalek.com/sitemap.xml\n');
  const missing = renderWritingHTML(template, [article], { ...options, notFound: true });
  await write('404.html', missing); await write('blog/__not-found.html', missing);
  assert.deepEqual((await validateSeo(root)).errors, []);
  await write(postFile, post.replace(`https://phixalek.com/blog/${article.slug}/`, 'https://phixalek.com/incorrect/'));
  await rm(new URL('media/demome-01.webp', root));
  await write('404.html', missing.replace('noindex, follow', 'index, follow'));
  const { errors } = await validateSeo(root);
  assert.ok(errors.some(error => error.includes('canonical differs')));
  assert.ok(errors.some(error => error.includes('missing or invalid social image')));
  assert.ok(errors.some(error => error.includes('404.html must be noindex')));
});
